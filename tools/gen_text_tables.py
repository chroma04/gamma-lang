#!/usr/bin/env python3
"""Generates the Unicode tables of std/text and its conformance test.

Usage: tools/gen_text_tables.py <ucd-dir>

<ucd-dir> holds these files of one version of the Unicode Character Database
(https://www.unicode.org/Public/<version>/ucd/), in the same layout:

    auxiliary/GraphemeBreakProperty.txt
    auxiliary/GraphemeBreakTest.txt
    emoji/emoji-data.txt
    DerivedCoreProperties.txt

It writes:

    lib/std/text/tables.gm                         the property table
    tests/conformance/run/std_text_ucd.gm          every case of GraphemeBreakTest.txt
    tests/conformance/run/std_text_ucd.stdout

Run it from the repository root, then `gamma fmt lib/std/text tests/conformance/run`.
"""

import os
import re
import sys

# The classes of the table, numbered as in lib/std/text/text.gm. The rules of UAX #29
# use Grapheme_Cluster_Break, Extended_Pictographic and Indic_Conjunct_Break; these
# properties are folded into one class per code point.
CLASSES = [
    "Other",
    "CR",
    "LF",
    "Control",
    "Extend",  # Grapheme_Cluster_Break=Extend and Indic_Conjunct_Break=None
    "ExtendInCB",  # Grapheme_Cluster_Break=Extend and Indic_Conjunct_Break=Extend
    "Linker",  # Grapheme_Cluster_Break=Extend and Indic_Conjunct_Break=Linker
    "ZWJ",
    "RegionalIndicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
    "Pictographic",  # Extended_Pictographic (and Grapheme_Cluster_Break=Other)
    "Consonant",  # Indic_Conjunct_Break=Consonant (and Grapheme_Cluster_Break=Other)
]
CLASS = {name: i for i, name in enumerate(CLASSES)}
MAX = 0x110000


def parse(path, want=None):
    """Yields (lo, hi, fields) for each data line of a UCD file."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            cps = fields[0].split("..")
            lo = int(cps[0], 16)
            hi = int(cps[-1], 16)
            if want is None or fields[1] == want:
                yield lo, hi, fields[1:]


def build(ucd):
    gcb = ["Other"] * MAX
    for lo, hi, f in parse(os.path.join(ucd, "auxiliary/GraphemeBreakProperty.txt")):
        name = {"Regional_Indicator": "RegionalIndicator"}.get(f[0], f[0])
        for c in range(lo, hi + 1):
            gcb[c] = name
    pict = [False] * MAX
    for lo, hi, _ in parse(os.path.join(ucd, "emoji/emoji-data.txt"), "Extended_Pictographic"):
        for c in range(lo, hi + 1):
            pict[c] = True
    incb = [None] * MAX
    for lo, hi, f in parse(os.path.join(ucd, "DerivedCoreProperties.txt"), "InCB"):
        for c in range(lo, hi + 1):
            incb[c] = f[1]

    cls = [0] * MAX
    for c in range(MAX):
        g = gcb[c]
        name = g
        if pict[c]:
            assert g == "Other", f"U+{c:04X}: Extended_Pictographic with GCB={g}"
            name = "Pictographic"
        if incb[c] == "Consonant":
            assert g == "Other" and not pict[c], f"U+{c:04X}: InCB=Consonant with GCB={g}"
            name = "Consonant"
        elif incb[c] == "Linker":
            assert g == "Extend", f"U+{c:04X}: InCB=Linker with GCB={g}"
            name = "Linker"
        elif incb[c] == "Extend":
            assert g in ("Extend", "ZWJ"), f"U+{c:04X}: InCB=Extend with GCB={g}"
            name = "ExtendInCB" if g == "Extend" else "ZWJ"
        elif g == "ZWJ":
            raise AssertionError("ZWJ is expected to be InCB=Extend")
        cls[c] = CLASS[name]
    # Hangul syllables alternate between LV and LVT; text.gm tells them apart
    # arithmetically, so the table gives the whole block as LVT.
    for c in range(0xAC00, 0xD7A4):
        want = "LV" if (c - 0xAC00) % 28 == 0 else "LVT"
        assert gcb[c] == want, f"U+{c:04X}: Hangul syllable with GCB={gcb[c]}"
        cls[c] = CLASS["LVT"]
    return cls


def version(path):
    with open(path, encoding="utf-8") as f:
        m = re.search(r"-(\d+\.\d+\.\d+)\.txt", f.readline())
    return m.group(1)


def write_table(cls, ver, out):
    # One entry per run of equal classes: the first code point of the run shifted left
    # by 8, ORed with the class.
    entries = []
    for c in range(MAX):
        if c == 0 or cls[c] != cls[c - 1]:
            entries.append((c << 8) | cls[c])
    lines = [
        "// Generated by tools/gen_text_tables.py from the Unicode Character Database",
        f"// {ver}. Do not edit.",
        "",
        f"/// The version of the Unicode Standard that grapheme clusters follow.",
        f"pub UNICODE_VERSION :: \"{ver}\"",
        "",
        "// The grapheme class of every code point, as runs: an entry is the first code point",
        "// of a run shifted left by 8, ORed with the class (the `CLASS_` constants in",
        "// text.gm) of every code point up to the next entry. The Hangul syllables",
        "// U+AC00..U+D7A3 are all given as LVT; the LV ones are found arithmetically.",
        "CLASS_RUNS :: [_]u32(",
    ]
    for i in range(0, len(entries), 6):
        lines.append("    " + ", ".join(f"0x{e:08x}" for e in entries[i : i + 6]) + ",")
    lines.append(")")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(entries)


def gamma_string(cps):
    out = []
    for c in cps:
        if 0x20 <= c < 0x7F and chr(c) not in '"\\':
            out.append(chr(c))
        else:
            out.append(f"\\u{{{c:x}}}")
    return '"' + "".join(out) + '"'


def write_test(ucd, ver, out):
    cases = []
    with open(os.path.join(ucd, "auxiliary/GraphemeBreakTest.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            clusters = [[int(x, 16) for x in part.split("×")] for part in line.split("÷")[1:-1]]
            cps = [c for cl in clusters for c in cl]
            lens = [sum(len(chr(c).encode("utf-8")) for c in cl) for cl in clusters]
            cases.append((cps, lens))
    lines = [
        "// Generated by tools/gen_text_tables.py from GraphemeBreakTest.txt of the Unicode",
        f"// Character Database {ver}. Do not edit.",
        "//",
        "// Every case of the test file: `text` and the byte lengths of its grapheme clusters,",
        "// one byte each, in `lens`.",
        "text :: import \"std/text\"",
        "",
        "Case :: struct {",
        "    text: string",
        "    lens: string",
        "}",
        "",
        "CASES :: [_]Case(",
    ]
    for cps, lens in cases:
        lens_s = "".join(f"\\x{n:02x}" for n in lens)
        lines.append(f"    Case(text: {gamma_string(cps)}, lens: \"{lens_s}\"),")
    lines += [
        ")",
        "",
        "main :: fn() \\ {Out} {",
        "    failed: usize = 0",
        "    for i, c in enumerate(CASES[..]) {",
        "        k: usize = 0",
        "        ok := true",
        "        for g in text.graphemes(c.text) {",
        "            if k >= c.lens.len or g.len is not usize(c.lens[k]) { ok = false }",
        "            k += 1",
        "        }",
        "        if k is not c.lens.len { ok = false }",
        "        if not ok {",
        "            print(\"case {} failed\\n\", i)",
        "            failed += 1",
        "        }",
        "    }",
        "    print(\"{} cases, {} failed\\n\", (CASES.len, failed))",
        "}",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(out[: -len(".gm")] + ".stdout", "w", encoding="utf-8") as f:
        f.write(f"{len(cases)} cases, 0 failed\n")
    return len(cases)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = sys.argv[1]
    ver = version(os.path.join(ucd, "auxiliary/GraphemeBreakProperty.txt"))
    n = write_table(build(ucd), ver, "lib/std/text/tables.gm")
    m = write_test(ucd, ver, "tests/conformance/run/std_text_ucd.gm")
    print(f"Unicode {ver}: {n} table entries, {m} test cases")


if __name__ == "__main__":
    main()
