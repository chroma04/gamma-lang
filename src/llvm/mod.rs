//! The experimental LLVM back end: translates a checked [`Program`] to textual LLVM IR,
//! which `clang` optimizes and compiles to an object linked with the C runtime.
//!
//! This back end exists to measure what LLVM's optimizer buys over the other back ends,
//! not to compile every program. It supports a subset of the language: scalar integers
//! (8 to 64 bits), `bool`, `f32` and `f64`, fixed-size arrays of them, pointers to those,
//! direct calls, the structured control flow (`if`, `while`, `for` over ranges,
//! `break`, `continue`, `return`) and `print` of scalars and string literals to the
//! ambient `Out`. Everything else is reported as an [`Unsupported`] error naming the
//! construct. Checks trap with the same messages as the other back ends, though without
//! the call trace a Debug build reports.
//!
//! IR is written as text rather than built through the LLVM C API, so the compiler links
//! no LLVM library: the only dependency is a `clang` on the `PATH` (or in
//! `GAMMA_LLVM_CLANG`) when a program is built. `GAMMA_LLVM_OPT` (0 to 3, default 2) picks
//! the optimization level and `GAMMA_DUMP_LLVM=1` prints the IR.

mod func;

use crate::cgen::{Options, Unsupported};
use crate::source::{SourceMap, Span};
use crate::tir::{FnId, Program};
use crate::toolchain::Toolchain;
use crate::types::{FloatTy, Ty, TyKind};
use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;
use std::path::Path;

pub type LResult<T> = Result<T, Unsupported>;

/// The error for a construct this back end cannot translate.
pub fn unsupported<T>(span: Span, what: impl Into<String>) -> LResult<T> {
    Err(Unsupported { message: format!("not supported by the LLVM back end: {}", what.into()), span })
}

/// The glue between generated code and the runtime, compiled with it.
const GLUE: &str = include_str!("../../runtime/gm_llvm.c");

/// The output of [`generate`]: the program as LLVM IR.
pub struct Generated {
    pub ir: String,
    pub opts: Options,
    pub target: crate::layout::Target,
}

/// Translates `prog` to an LLVM module whose `gm_ll_main` runs `entry`.
pub fn generate(prog: &Program, sources: &SourceMap, entry: FnId, opts: &Options) -> LResult<Generated> {
    let triple = crate::clif::check_target(&prog.target).map_err(|m| Unsupported { message: m, span: Span::DUMMY })?;
    if opts.debug_info {
        return unsupported(Span::DUMMY, "debug information (`-g`); use `--backend=c`");
    }
    let def = &prog.fns[entry.index()];
    if !(def.ret.is_unit() || def.ret.is_never()) {
        return unsupported(def.span, format!("a `main` returning `{}`", def.ret));
    }
    let mut g = Gen {
        prog,
        sources,
        opts: opts.clone(),
        consts: String::new(),
        strs: HashMap::new(),
        files: HashMap::new(),
        queue: vec![entry],
        queued: HashSet::from([entry]),
        fns: String::new(),
        intrinsics: BTreeSet::new(),
    };
    while let Some(id) = g.queue.pop() {
        func::define(&mut g, id)?;
    }
    let mut ir = String::new();
    let _ = writeln!(ir, "; Gamma program, generated by the gamma LLVM back end");
    let _ = writeln!(ir, "target triple = \"{triple}\"\n");
    ir.push_str(RUNTIME_DECLS);
    for d in &g.intrinsics {
        let _ = writeln!(ir, "{d}");
    }
    let _ = writeln!(ir, "@gm_ll_debug = constant i8 {}", opts.debug as u8);
    let _ = writeln!(ir, "@gm_ll_checks = constant i8 {}\n", opts.checks as u8);
    ir.push_str(&g.consts);
    ir.push('\n');
    ir.push_str(&g.fns);
    let _ = writeln!(ir, "define void @gm_ll_main() {{\n  call void @{}()\n  ret void\n}}", fn_name(entry));
    ir.push_str(ATTRS);
    if std::env::var_os("GAMMA_DUMP_LLVM").is_some_and(|v| v == "1") {
        eprintln!("{ir}");
    }
    Ok(Generated { ir, opts: opts.clone(), target: prog.target.clone() })
}

/// The runtime functions the generated code calls.
const RUNTIME_DECLS: &str = "\
declare void @gm_trap(ptr, ptr, i32, i32) #1
declare void @gm_ll_trap_index(i64, i64, ptr, i32, i32) #1
declare void @gm_ll_trap_shift(i64, ptr, ptr, i32, i32) #1
declare void @gm_stack_overflow() #1
@gm_stack_limit = external thread_local global i64
declare void @gm_write_out(ptr, i64)
declare void @gm_ll_write_int(i64, i32, i32)
declare void @gm_ll_write_f64(double)
declare void @gm_ll_write_f32(float)
declare void @gm_ll_write_bool(i8)

";

const ATTRS: &str = "\nattributes #1 = { cold noreturn nounwind }\n";

/// The symbol of a Gamma function.
fn fn_name(id: FnId) -> String {
    format!("gm_f{}", id.0)
}

/// Module-wide state: the functions written so far and the constants they use.
pub(crate) struct Gen<'a> {
    prog: &'a Program,
    sources: &'a SourceMap,
    opts: Options,
    /// Definitions of string constants.
    consts: String,
    strs: HashMap<Vec<u8>, String>,
    /// The constant holding each source file's path, for trap locations.
    files: HashMap<u32, String>,
    /// Functions referenced but not yet written.
    queue: Vec<FnId>,
    queued: HashSet<FnId>,
    /// The function definitions.
    fns: String,
    /// Declarations of the LLVM intrinsics used.
    intrinsics: BTreeSet<String>,
}

impl Gen<'_> {
    /// The name of the LLVM intrinsic `llvm.<name>`, declared with the result type `ret`
    /// and the parameter types `params`.
    fn intrinsic(&mut self, ret: &str, name: &str, params: &str) -> String {
        self.intrinsics.insert(format!("declare {ret} @llvm.{name}({params})"));
        format!("@llvm.{name}")
    }

    /// The name of a function, scheduling its definition.
    fn func(&mut self, id: FnId) -> String {
        if self.queued.insert(id) {
            self.queue.push(id);
        }
        fn_name(id)
    }

    /// A private constant holding `bytes` followed by a NUL (so it is also a C string).
    fn bytes(&mut self, bytes: &[u8]) -> String {
        if let Some(n) = self.strs.get(bytes) {
            return n.clone();
        }
        let name = format!("@.s{}", self.strs.len());
        let mut lit = String::new();
        for &b in bytes.iter().chain(std::iter::once(&0)) {
            if b.is_ascii_graphic() && b != b'"' && b != b'\\' || b == b' ' {
                lit.push(b as char);
            } else {
                let _ = write!(lit, "\\{b:02X}");
            }
        }
        let _ = writeln!(self.consts, "{name} = private unnamed_addr constant [{} x i8] c\"{lit}\"", bytes.len() + 1);
        self.strs.insert(bytes.to_vec(), name.clone());
        name
    }

    /// The location arguments of a trap at `span`: file, line and column.
    fn loc(&mut self, span: Span) -> String {
        if span == Span::DUMMY {
            return "ptr null, i32 0, i32 0".into();
        }
        let file = match self.files.get(&span.file.0) {
            Some(f) => f.clone(),
            None => {
                let path = self.sources.file(span.file).path.display().to_string();
                let f = self.bytes(path.as_bytes());
                self.files.insert(span.file.0, f.clone());
                f
            }
        };
        let (line, col) = self.sources.file(span.file).line_col(span.lo);
        format!("ptr {file}, i32 {line}, i32 {col}")
    }

    /// The width and signedness of an integer type.
    fn int(&self, ty: Ty) -> Option<(bool, u32)> {
        crate::layout::int_bits(ty, &self.prog.target)
    }

    /// The LLVM type of values of `ty`; `void` for `()` and `never`.
    fn llty(&self, ty: Ty, span: Span) -> LResult<String> {
        if let Some((_, bits)) = self.int(ty) {
            return match bits {
                8 | 16 | 32 | 64 => Ok(format!("i{bits}")),
                _ => unsupported(span, format!("the integer type `{ty}`")),
            };
        }
        Ok(match ty.kind() {
            TyKind::Bool => "i1".into(),
            TyKind::Float(FloatTy::F32) => "float".into(),
            TyKind::Float(FloatTy::F64) => "double".into(),
            TyKind::Never => "void".into(),
            TyKind::Tuple { elems, .. } if elems.is_empty() => "void".into(),
            TyKind::Ptr { pointee, .. } if self.storable(*pointee) => "ptr".into(),
            TyKind::Array { len, elem, kind: crate::types::ArrayKind::Plain } if self.storable(*elem) => {
                format!("[{len} x {}]", self.llty(*elem, span)?)
            }
            _ => return unsupported(span, format!("values of type `{ty}`")),
        })
    }

    /// Whether values of `ty` have an LLVM type other than `void`.
    fn storable(&self, ty: Ty) -> bool {
        self.llty(ty, Span::DUMMY).is_ok_and(|t| t != "void")
    }
}

/// The `clang` that compiles the IR.
fn clang() -> std::ffi::OsString {
    std::env::var_os("GAMMA_LLVM_CLANG").unwrap_or_else(|| "clang".into())
}

/// The optimization level from `GAMMA_LLVM_OPT`.
pub fn opt_level() -> Result<u8, String> {
    match std::env::var("GAMMA_LLVM_OPT") {
        Err(_) => Ok(2),
        Ok(v) => match v.parse::<u8>() {
            Ok(n) if n <= 3 => Ok(n),
            _ => Err(format!("gamma: GAMMA_LLVM_OPT must be 0, 1, 2 or 3, not `{v}`")),
        },
    }
}

/// The runtime and its glue for this back end, as one C source.
pub fn runtime_source() -> String {
    format!("{}\n{}\n", crate::cgen::separate_runtime_source(), GLUE)
}

/// Compiles the IR of `generated` with clang and links it with the runtime into the
/// executable `exe`, with the C compiler of `toolchain` as the linker driver.
pub fn compile(
    generated: &Generated,
    toolchain: &Toolchain,
    link: &crate::cgen::Link,
    exe: &Path,
) -> Result<(), String> {
    use crate::cgen::{Scratch, scratch_path};
    let level = opt_level()?;
    let ll = scratch_path(exe, "gamma", "ll");
    let obj = scratch_path(exe, "gamma", "o");
    let rt_obj = scratch_path(exe, "rt", "o");
    let _scratch = Scratch(vec![ll.clone(), obj.clone(), rt_obj.clone()]);
    std::fs::write(&ll, &generated.ir).map_err(|e| format!("cannot write {}: {}", ll.display(), e))?;
    let out = std::process::Command::new(clang())
        .args(["-x", "ir", "-c", "-fPIC", "-Wno-override-module", &format!("-O{level}"), "-o"])
        .arg(&obj)
        .arg(&ll)
        .output()
        .map_err(|e| format!("cannot run clang (set GAMMA_LLVM_CLANG to choose another): {e}"))?;
    if !out.status.success() {
        return Err(format!("clang failed on the generated IR:\n{}", String::from_utf8_lossy(&out.stderr)));
    }
    let rt_flags = crate::cgen::rt_flags(&generated.opts, &generated.target);
    let source = runtime_source();
    let runtime = match crate::cgen::runtime_object_from(toolchain, &rt_flags, &source, "gm_llvm_rt") {
        Some(o) => o,
        None => {
            let c = scratch_path(exe, "rt", "c");
            let _c = Scratch(vec![c.clone()]);
            std::fs::write(&c, &source).map_err(|e| format!("cannot write {}: {}", c.display(), e))?;
            let out = toolchain
                .command(&rt_flags)
                .arg("-c")
                .arg("-o")
                .arg(&rt_obj)
                .arg(&c)
                .output()
                .map_err(|e| format!("cannot run the C compiler `{}`: {}", toolchain.display(), e))?;
            if !out.status.success() {
                return Err(format!("the C compiler failed:\n{}", String::from_utf8_lossy(&out.stderr)));
            }
            rt_obj.clone()
        }
    };
    let mut flags: Vec<String> = crate::cgen::base_cflags(&generated.target).iter().map(|s| s.to_string()).collect();
    if generated.target.os == "Linux" {
        flags.push("-pie".into());
    }
    let out = toolchain
        .command(&flags)
        .arg("-o")
        .arg(exe)
        .arg(&obj)
        .arg(&runtime)
        .args(&link.objects)
        .args(&toolchain.ldflags)
        .arg("-lm")
        .output()
        .map_err(|e| format!("cannot run the C compiler `{}`: {}", toolchain.display(), e))?;
    if !out.status.success() {
        return Err(format!("linking failed:\n{}", String::from_utf8_lossy(&out.stderr)));
    }
    Ok(())
}
