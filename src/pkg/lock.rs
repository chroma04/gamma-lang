//! The lockfile, `gamma.lock`: the exact revision and content hash of every git
//! package and the content hash of every archive package in a dependency graph.

use std::fmt::Write as _;
use std::path::Path;
use toml_edit::{Document, Item, Value};

pub const HEADER: &str = "# This file is generated by `gamma`. Do not edit it by hand.";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    /// The normalized repository URL (the lockfile writes it as `git+URL`); for an
    /// archive, `url+` and its URL (the lockfile writes that as it is).
    pub url: String,
    /// The directory of the package in the repository, if not the root.
    pub subdir: Option<String>,
    /// The version of the tag it was resolved from, when it came from a version requirement.
    pub version: Option<String>,
    /// What the manifest asked for, resolved: `tag=…`, `branch=…`, `rev=…` or `default`.
    pub reference: String,
    /// The full commit id (empty for an archive).
    pub rev: String,
    /// For an archive, `sha256:` and the hash of the downloaded file.
    pub archive: Option<String>,
    /// `sha256:` and the hash of the checked-out tree.
    pub checksum: String,
    /// The names of the locked packages it depends on.
    pub dependencies: Vec<String>,
}

impl LockedPackage {
    /// Whether this is an archive (`url = …`) rather than a git package.
    pub fn is_archive(&self) -> bool {
        self.archive.is_some()
    }

    pub fn key(&self) -> (&str, Option<&str>) {
        (&self.url, self.subdir.as_deref())
    }

    /// How the package is shown in progress messages: `v1.2.3` or a short revision.
    pub fn display_version(&self) -> String {
        if let Some(a) = &self.archive {
            let hash = a.strip_prefix("sha256:").unwrap_or(a);
            return format!("archive {}", &hash[..hash.len().min(12)]);
        }
        match &self.version {
            Some(v) => format!("v{}", v),
            None => format!("{} @ {}", self.reference, &self.rev[..self.rev.len().min(12)]),
        }
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lock {
    pub packages: Vec<LockedPackage>,
}

fn quote(s: &str) -> String {
    Value::from(s).to_string().trim().to_string()
}

impl Lock {
    pub fn find(&self, url: &str, subdir: Option<&str>) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.key() == (url, subdir))
    }

    /// The text of the file: entries sorted by name, then source, deterministic.
    pub fn render(&self) -> String {
        let mut pkgs: Vec<&LockedPackage> = self.packages.iter().collect();
        pkgs.sort_by(|a, b| (&a.name, &a.url, &a.subdir).cmp(&(&b.name, &b.url, &b.subdir)));
        let mut out = format!("{}\nversion = 1\n", HEADER);
        for p in pkgs {
            let _ = writeln!(out, "\n[[package]]\nname = {}", quote(&p.name));
            let source = if p.is_archive() { p.url.clone() } else { format!("git+{}", p.url) };
            let _ = writeln!(out, "source = {}", quote(&source));
            if let Some(s) = &p.subdir {
                let _ = writeln!(out, "subdir = {}", quote(s));
            }
            if let Some(a) = &p.archive {
                let _ = writeln!(out, "archive = {}", quote(a));
            } else {
                if let Some(v) = &p.version {
                    let _ = writeln!(out, "version = {}", quote(v));
                }
                let _ = writeln!(out, "reference = {}", quote(&p.reference));
                let _ = writeln!(out, "rev = {}", quote(&p.rev));
            }
            let _ = writeln!(out, "checksum = {}", quote(&p.checksum));
            let mut deps = p.dependencies.clone();
            deps.sort();
            deps.dedup();
            let list: Vec<String> = deps.iter().map(|d| quote(d)).collect();
            let _ = writeln!(out, "dependencies = [{}]", list.join(", "));
        }
        out
    }

    pub fn parse(text: &str) -> Result<Lock, String> {
        let doc = Document::parse(text).map_err(|e| e.to_string().trim().to_string())?;
        match doc.get("version").and_then(Item::as_integer) {
            Some(1) => {}
            Some(v) => return Err(format!("unsupported lockfile version {}", v)),
            None => return Err("missing `version`".into()),
        }
        let mut lock = Lock::default();
        let Some(pkgs) = doc.get("package") else { return Ok(lock) };
        let tables = pkgs.as_array_of_tables().ok_or("`package` must be an array of tables")?;
        for t in tables.iter() {
            let get = |k: &str| -> Result<String, String> {
                t.get(k)
                    .and_then(Item::as_str)
                    .map(str::to_string)
                    .ok_or_else(|| format!("a package entry needs a string `{}`", k))
            };
            let source = get("source")?;
            let archive = t.get("archive").and_then(Item::as_str).map(str::to_string);
            let url = if let Some(u) = source.strip_prefix("git+") {
                u.to_string()
            } else if source.starts_with("url+") && archive.is_some() {
                source.clone()
            } else {
                return Err(format!("unsupported source `{}`", source));
            };
            let text =
                |k: &str| -> Result<String, String> { if archive.is_some() { Ok(String::new()) } else { get(k) } };
            let dependencies = match t.get("dependencies") {
                None => vec![],
                Some(d) => d
                    .as_array()
                    .ok_or("`dependencies` must be an array")?
                    .iter()
                    .map(|v| v.as_str().map(str::to_string).ok_or("`dependencies` holds strings"))
                    .collect::<Result<_, _>>()?,
            };
            lock.packages.push(LockedPackage {
                name: get("name")?,
                url,
                subdir: t.get("subdir").and_then(Item::as_str).map(str::to_string),
                version: t.get("version").and_then(Item::as_str).map(str::to_string),
                reference: text("reference")?,
                rev: text("rev")?,
                archive,
                checksum: get("checksum")?,
                dependencies,
            });
        }
        Ok(lock)
    }

    /// Reads `path`; a missing file is `Ok(None)`.
    pub fn read(path: &Path) -> Result<Option<Lock>, String> {
        match std::fs::read_to_string(path) {
            Ok(t) => Lock::parse(&t).map(Some).map_err(|e| format!("{}: {}", path.display(), e)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(format!("cannot read {}: {}", path.display(), e)),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pkg(name: &str, url: &str) -> LockedPackage {
        LockedPackage {
            name: name.into(),
            url: url.into(),
            subdir: None,
            version: Some("1.2.3".into()),
            reference: "tag=v1.2.3".into(),
            rev: "a".repeat(40),
            archive: None,
            checksum: format!("sha256:{}", "b".repeat(64)),
            dependencies: vec!["util".into(), "app".into()],
        }
    }

    #[test]
    fn round_trip_and_order() {
        let mut sub = pkg("http", "https://h/z");
        sub.subdir = Some("pkg/http".into());
        sub.version = None;
        sub.reference = "default".into();
        let a = Lock { packages: vec![pkg("util", "https://h/u"), sub.clone(), pkg("http", "https://h/a")] };
        let b = Lock { packages: vec![pkg("http", "https://h/a"), pkg("util", "https://h/u"), sub] };
        assert_eq!(a.render(), b.render());
        let text = a.render();
        assert!(text.starts_with(HEADER));
        assert!(text.find("https://h/a").unwrap() < text.find("https://h/z").unwrap());
        assert!(text.contains("dependencies = [\"app\", \"util\"]"));
        let back = Lock::parse(&text).unwrap();
        assert_eq!(back.render(), text);
        assert_eq!(back.packages.len(), 3);
        assert!(back.find("https://h/z", Some("pkg/http")).is_some());
        assert!(back.find("https://h/z", None).is_none());
    }

    #[test]
    fn archive_entries() {
        let mut a = pkg("blob", "url+https://h/blob-1.0.tar.gz");
        a.version = None;
        a.reference = String::new();
        a.rev = String::new();
        a.archive = Some(format!("sha256:{}", "c".repeat(64)));
        let lock = Lock { packages: vec![a.clone(), pkg("util", "https://h/u")] };
        let text = lock.render();
        assert!(text.contains("source = \"url+https://h/blob-1.0.tar.gz\""), "{}", text);
        assert!(text.contains(&format!("archive = \"sha256:{}\"", "c".repeat(64))));
        let back = Lock::parse(&text).unwrap();
        assert_eq!(back.render(), text);
        let found = back.find("url+https://h/blob-1.0.tar.gz", None).unwrap();
        assert!(found.is_archive() && found.rev.is_empty());
        assert!(found.display_version().starts_with("archive cccccccccccc"));
        // An archive source needs its hash.
        assert!(Lock::parse("version = 1\n[[package]]\nname = \"a\"\nsource = \"url+x\"\nchecksum = \"c\"\n").is_err());
    }

    #[test]
    fn rejects_bad_files() {
        assert!(Lock::parse("version = 2\n").unwrap_err().contains("unsupported"));
        assert!(Lock::parse("[[package]]\nname = \"a\"\n").is_err());
        assert!(Lock::parse("version = 1\n[[package]]\nname = \"a\"\n").is_err());
        assert_eq!(Lock::parse(&Lock::default().render()).unwrap(), Lock::default());
    }
}
